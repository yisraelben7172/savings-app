import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DealsService } from '../src/deals/deals.service';
import { PrismaService } from '../src/prisma/prisma.service';
import { SearchService } from '../src/search/search.service';
import { seedCatalog, DEALS } from './eval/catalog';
import { CASES } from './eval/cases';
import { runAll, scoreClaims, summarize } from './eval/harness';

const prisma = new PrismaService();
const search = new SearchService(prisma, new DealsService(prisma));
const NOW = new Date();

describe('search evaluation (synthetic catalog, real database)', () => {
  beforeAll(() => seedCatalog(prisma, NOW));
  afterAll(() => prisma.$disconnect());

  it('answers the labeled shopping questions correctly, and never breaks a hard limit', async () => {
    const runs = await runAll(search, NOW);
    const s = summarize(runs);
    const claims = scoreClaims(runs);

    // Run twice: same question, same answer, same order.
    const again = await runAll(search, NOW);
    const consistent = runs.filter((r, i) => JSON.stringify(r.slugs) === JSON.stringify(again[i].slugs)).length;

    // Commission-blind: approve programs for every store and pile commissions and clicks onto the worst-ranked results.
    const merchants = await prisma.merchant.findMany();
    const programs = await Promise.all(
      merchants.map((m) => prisma.affiliateProgram.create({
        data: { merchantId: m.id, network: 'impact', name: `${m.name} via Impact`, status: 'APPROVED', linkMethod: 'DEEPLINK_TEMPLATE', linkTemplate: 'https://go.network.test/c?u={urlEncoded}&sid={clickId}', allowedTrackingHosts: ['network.test'] },
      })),
    );
    const offers = await prisma.offer.findMany({ where: { deal: { slug: { in: ['hp-pavilion', 'hoka-clifton', 'led-desk-lamp', 'miami-hotel', 'dell-inspiron'] } } } });
    for (const [i, o] of offers.entries()) {
      const program = programs.find((p) => p.merchantId === o.merchantId)!;
      const click = await prisma.click.create({ data: { offerId: o.id, programId: program.id, outcome: 'TRACKED' } });
      await prisma.commission.create({ data: { programId: program.id, externalId: `big-${i}`, clickId: click.id, status: 'PAID', amount: 5000, saleAmount: 100000, occurredAt: NOW } });
    }
    const afterCommissions = await runAll(search, NOW);
    const blind = runs.filter((r, i) => JSON.stringify(r.slugs) === JSON.stringify(afterCommissions[i].slugs) && JSON.stringify(r.facts) === JSON.stringify(afterCommissions[i].facts)).length;

    const table = {
      'catalog deals (synthetic)': DEALS.length,
      'questions': s.cases,
      'questions answered correctly': `${s.casesPassed}/${s.cases}`,
      'hard-limit violations (budget, brand, category, exclusions)': s.hardConstraintViolations,
      'hidden items shown (stale, out of stock, unapproved, disabled, Gold, AI-restricted)': s.neverShownViolations,
      'expected deals found': s.expectedFound,
      'right deal ranked first': `${Math.round(s.top1 * 100)}%`,
      'ranking order pairs correct': s.orderingPairs,
      'no-result answers correct': s.emptyAnswersCorrect,
      'same answer when asked twice': `${consistent}/${runs.length}`,
      'same answer with huge commissions on rivals': `${blind}/${runs.length}`,
      'invented prices, discounts or stores caught': `${claims.inventedCaught}/${claims.inventedReplies}`,
      'honest replies wrongly flagged': `${claims.honestFlagged}/${claims.honestReplies}`,
    };
    console.table(table);
    for (const v of s.verdicts.filter((x) => !x.passed)) console.log(`FAILED ${v.id} ("${v.ask}"): ${v.failures.join('; ')}`);
    for (const m of claims.missed) console.log(`CLAIM NOT CAUGHT: ${m}`);
    for (const m of claims.wronglyFlagged) console.log(`HONEST REPLY FLAGGED: ${m}`);

    if (process.env.WRITE_EVAL_REPORT) {
      const rows = Object.entries(table).map(([k, v]) => `| ${k} | ${v} |`).join('\n');
      const detail = s.verdicts.map((v) => `| ${v.id} | ${v.ask} | ${v.passed ? 'pass' : 'FAIL'} | ${v.results.join(', ') || 'none'} |`).join('\n');
      writeFileSync(
        join(__dirname, '..', 'docs', 'evaluation-results.md'),
        `# Search evaluation results\n\nGenerated by \`npm run eval\` on ${NOW.toISOString().slice(0, 10)}. The catalog is **synthetic** (invented products and prices written for this test); it measures the search and safety rules, not any real retailer.\n\n| Measure | Result |\n|---|---|\n${rows}\n\n## Every question\n\n| Case | Shopper asks | Result | Deals returned, best first |\n|---|---|---|---|\n${detail}\n`,
      );
    }

    expect(s.hardConstraintViolations).toBe(0);
    expect(s.neverShownViolations).toBe(0);
    expect(s.casesPassed).toBe(s.cases);
    expect(s.recall).toBe(1);
    expect(consistent).toBe(runs.length);
    expect(blind).toBe(runs.length);
    expect(claims.inventedCaught).toBe(claims.inventedReplies);
    expect(claims.honestFlagged).toBe(0);
    expect(CASES.length).toBeGreaterThanOrEqual(30);
  });
});
